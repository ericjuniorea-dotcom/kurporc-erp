"use client";

import { useState, useEffect, useCallback } from "react";
import { useSession } from "next-auth/react";
import { useRouter } from "next/navigation";
import { Topbar } from "@/components/layout/topbar";
import {
  IconTrendingUp, IconPlus, IconLoader2, IconAlertTriangle,
  IconCheck, IconX, IconPackage,
} from "@tabler/icons-react";

const ALLOWED = [1, 2, 4, 6];

interface FormulaOption {
  id: string;
  name: string;
  feedType: { name: string; phase: string };
  versions: Array<{ id: string; versionNumber: number }>;
}

interface Orden {
  id: string;
  scheduledDate: string;
  quantityKg: number;
  status: "PENDING" | "CONFIRMED" | "PRODUCED" | "CANCELLED";
  isAutoGenerated: boolean;
  producedAt: string | null;
  feedTypeName: string;
  phase: string;
  formulaVersionNumber: number;
  loteInventario: { id: string; numeroLote: string; cantidadActual: number } | null;
}

const ESTADO_LABEL: Record<string, { label: string; bg: string; color: string }> = {
  PENDING:   { label: "Pendiente",  bg: "var(--warning-subtle)", color: "var(--warning-text)" },
  CONFIRMED: { label: "Confirmada", bg: "var(--info-subtle)",    color: "var(--info-text)" },
  PRODUCED:  { label: "Producida",  bg: "var(--success-subtle)", color: "var(--success-text)" },
  CANCELLED: { label: "Cancelada",  bg: "var(--bg-overlay)",     color: "var(--text-muted)" },
};

function todayStr() { return new Date().toISOString().split("T")[0]; }

export default function ProduccionBalanceadoPage() {
  const { data: session, status } = useSession();
  const router = useRouter();

  const [formulas, setFormulas] = useState<FormulaOption[]>([]);
  const [ordenes,  setOrdenes]  = useState<Orden[]>([]);
  const [loading,  setLoading]  = useState(true);
  const [msg,      setMsg]      = useState<string | null>(null);
  const [err,      setErr]      = useState<string | null>(null);
  const [procesando, setProcesando] = useState<string | null>(null);

  const [form, setForm] = useState({ formulaVersionId: "", scheduledDate: todayStr(), quantityKg: "" });
  const [saving, setSaving] = useState(false);

  const canEdit = session?.user.roles.some(r => ALLOWED.includes(r)) ?? false;

  const showMsg = (m: string) => { setMsg(m); setTimeout(() => setMsg(null), 3500); };

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const [fRes, oRes] = await Promise.all([fetch("/api/formulas"), fetch("/api/balanceado/produccion")]);
      const [fd, od] = await Promise.all([fRes.json(), oRes.json()]);
      if (Array.isArray(fd)) setFormulas(fd.filter((f: FormulaOption) => f.versions.length > 0));
      if (Array.isArray(od)) setOrdenes(od);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    if (status === "unauthenticated") { router.push("/login"); return; }
    if (status === "authenticated" && !canEdit) { router.push("/balanceado"); return; }
    if (status === "authenticated") load();
  }, [status, canEdit, router, load]);

  async function submitOrden(e: React.FormEvent) {
    e.preventDefault();
    setErr(null);
    if (!form.formulaVersionId || !form.quantityKg || Number(form.quantityKg) <= 0) {
      setErr("Elegí una fórmula y una cantidad válida"); return;
    }
    setSaving(true);
    const res = await fetch("/api/balanceado/produccion", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        formulaVersionId: form.formulaVersionId,
        scheduledDate: form.scheduledDate,
        quantityKg: Number(form.quantityKg),
      }),
    });
    setSaving(false);
    if (res.ok) {
      setForm({ formulaVersionId: "", scheduledDate: todayStr(), quantityKg: "" });
      showMsg("Orden de producción creada");
      load();
    } else {
      const d = await res.json();
      setErr(d.error ?? "Error al crear la orden");
    }
  }

  async function procesar(id: string, nuevoStatus: "PRODUCED" | "CANCELLED") {
    setProcesando(id); setErr(null);
    const res = await fetch(`/api/balanceado/produccion/${id}`, {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: nuevoStatus }),
    });
    setProcesando(null);
    if (res.ok) {
      showMsg(nuevoStatus === "PRODUCED" ? "Orden marcada como producida — stock actualizado" : "Orden cancelada");
      load();
    } else {
      const d = await res.json();
      if (d.detalle) {
        setErr(`${d.error}: ${d.detalle.map((x: { producto: string; necesario: number; disponible: number }) => `${x.producto} (necesita ${x.necesario}, hay ${x.disponible})`).join("; ")}`);
      } else {
        setErr(d.error ?? "Error al procesar la orden");
      }
    }
  }

  if (status === "loading" || !session) return null;

  return (
    <>
      <Topbar title="Órdenes de producción" icon={IconTrendingUp} iconColor="var(--success)" />
      <div style={{ padding: "16px 20px", display: "flex", flexDirection: "column", gap: 14 }}>
        {msg && <div className="kp-alert kp-alert-ok"><IconCheck size={13} /> {msg}</div>}
        {err && <div className="kp-alert kp-alert-danger"><IconAlertTriangle size={13} /> {err}</div>}

        {canEdit && (
          <form onSubmit={submitOrden} style={{ background: "var(--bg-surface)", border: "0.5px solid var(--border-default)", borderRadius: "var(--radius-lg)", padding: 16, maxWidth: 620 }}>
            <div style={{ fontSize: 13, fontWeight: 500, color: "var(--text-primary)", marginBottom: 12 }}>Nueva orden</div>
            <div style={{ display: "grid", gridTemplateColumns: "2fr 1fr 1fr", gap: 10, alignItems: "end" }}>
              <div>
                <label className="kp-label">Fórmula (versión activa) *</label>
                <select className="kp-input" style={{ appearance: "auto" }} value={form.formulaVersionId} onChange={e => setForm(f => ({ ...f, formulaVersionId: e.target.value }))}>
                  <option value="">— Seleccionar —</option>
                  {formulas.map(f => (
                    <option key={f.id} value={f.versions[0].id}>
                      {f.feedType.name} ({f.feedType.phase}) — v{f.versions[0].versionNumber}
                    </option>
                  ))}
                </select>
              </div>
              <div>
                <label className="kp-label">Fecha</label>
                <input type="date" className="kp-input" value={form.scheduledDate} onChange={e => setForm(f => ({ ...f, scheduledDate: e.target.value }))} />
              </div>
              <div>
                <label className="kp-label">Cantidad (kg) *</label>
                <input type="number" min="1" step="1" className="kp-input" value={form.quantityKg} onChange={e => setForm(f => ({ ...f, quantityKg: e.target.value }))} />
              </div>
            </div>
            <div style={{ display: "flex", justifyContent: "flex-end", marginTop: 12 }}>
              <button type="submit" className="btn btn-primary" disabled={saving} style={{ height: 30, fontSize: 12 }}>
                {saving ? <IconLoader2 size={13} style={{ animation: "spin 1s linear infinite" }} /> : <IconPlus size={13} />}
                {saving ? "Creando…" : "Crear orden"}
              </button>
            </div>
          </form>
        )}

        {loading ? (
          <div style={{ display: "flex", justifyContent: "center", padding: "48px 0" }}>
            <IconLoader2 size={24} style={{ color: "var(--text-muted)", animation: "spin 1s linear infinite" }} />
          </div>
        ) : ordenes.length === 0 ? (
          <div style={{ textAlign: "center", padding: "48px 0", background: "var(--bg-surface)", border: "0.5px solid var(--border-default)", borderRadius: "var(--radius-lg)" }}>
            <IconPackage size={32} style={{ color: "var(--text-muted)", display: "block", margin: "0 auto 8px" }} />
            <div style={{ fontSize: 12, color: "var(--text-secondary)" }}>Sin órdenes de producción todavía</div>
          </div>
        ) : (
          <div style={{ background: "var(--bg-surface)", border: "0.5px solid var(--border-default)", borderRadius: "var(--radius-lg)", overflow: "hidden" }}>
            {ordenes.map(o => {
              const cfg = ESTADO_LABEL[o.status];
              return (
                <div key={o.id} style={{ padding: "10px 14px", borderBottom: "0.5px solid var(--border-default)", display: "flex", alignItems: "center", justifyContent: "space-between", gap: 10 }}>
                  <div>
                    <div style={{ fontSize: 12, fontWeight: 500, color: "var(--text-primary)", display: "flex", alignItems: "center", gap: 8 }}>
                      {o.feedTypeName} ({o.phase}) — v{o.formulaVersionNumber}
                      <span className="badge" style={{ background: cfg.bg, color: cfg.color, border: "none", fontSize: 10 }}>{cfg.label}</span>
                      {o.isAutoGenerated && <span style={{ fontSize: 9, color: "var(--text-muted)" }}>(auto)</span>}
                    </div>
                    <div style={{ fontSize: 11, color: "var(--text-muted)", marginTop: 2 }}>
                      {new Date(o.scheduledDate).toLocaleDateString("es-PY")} · {o.quantityKg} kg
                      {o.loteInventario && ` · Lote ${o.loteInventario.numeroLote}`}
                    </div>
                  </div>
                  {canEdit && (o.status === "PENDING" || o.status === "CONFIRMED") && (
                    <div style={{ display: "flex", gap: 6, flexShrink: 0 }}>
                      <button className="btn" style={{ height: 26, fontSize: 10, color: "var(--danger-text)" }} disabled={procesando === o.id} onClick={() => procesar(o.id, "CANCELLED")}>
                        <IconX size={11} /> Cancelar
                      </button>
                      <button className="btn btn-primary" style={{ height: 26, fontSize: 10 }} disabled={procesando === o.id} onClick={() => procesar(o.id, "PRODUCED")}>
                        {procesando === o.id ? <IconLoader2 size={11} style={{ animation: "spin 1s linear infinite" }} /> : <IconCheck size={11} />}
                        Marcar producida
                      </button>
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        )}
      </div>
      <style>{`@keyframes spin { from { transform:rotate(0deg); } to { transform:rotate(360deg); } }`}</style>
    </>
  );
}
