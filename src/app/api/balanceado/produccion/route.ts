import { NextRequest, NextResponse } from "next/server";
import { getServerSession } from "next-auth";
import { authOptions } from "@/lib/auth/config";
import prisma from "@/lib/db/prisma";

export async function GET() {
  const session = await getServerSession(authOptions);
  if (!session) return NextResponse.json({ error: "No autenticado" }, { status: 401 });

  const ordenes = await prisma.balProductionOrder.findMany({
    where: { tenantId: session.user.tenantId },
    include: {
      formulaVersion: { include: { formula: { include: { feedType: { select: { name: true, phase: true } } } } } },
      loteInventario: { select: { id: true, numeroLote: true, cantidadActual: true } },
    },
    orderBy: { createdAt: "desc" },
  });

  return NextResponse.json(ordenes.map(o => ({
    id: o.id,
    scheduledDate: o.scheduledDate,
    quantityKg: Number(o.quantityKg),
    status: o.status,
    isAutoGenerated: o.isAutoGenerated,
    producedAt: o.producedAt,
    feedTypeName: o.formulaVersion.formula.feedType.name,
    phase: o.formulaVersion.formula.feedType.phase,
    formulaVersionNumber: o.formulaVersion.versionNumber,
    loteInventario: o.loteInventario,
  })));
}

export async function POST(req: NextRequest) {
  const session = await getServerSession(authOptions);
  if (!session) return NextResponse.json({ error: "No autenticado" }, { status: 401 });

  const allowed = [1, 2, 4, 6];
  if (!session.user.roles.some((r) => allowed.includes(r))) {
    return NextResponse.json({ error: "Sin permiso" }, { status: 403 });
  }

  const body = await req.json();
  const { formulaVersionId, scheduledDate, quantityKg, isAutoGenerated } = body as {
    formulaVersionId?: string; scheduledDate?: string; quantityKg?: number; isAutoGenerated?: boolean;
  };
  if (!formulaVersionId || !scheduledDate || !quantityKg || quantityKg <= 0) {
    return NextResponse.json({ error: "formulaVersionId, scheduledDate y quantityKg (>0) son requeridos" }, { status: 400 });
  }

  const tenantId = session.user.tenantId;
  const version = await prisma.formulaVersion.findFirst({ where: { id: formulaVersionId, tenantId } });
  if (!version) return NextResponse.json({ error: "Versión de fórmula no encontrada" }, { status: 404 });
  if (version.status !== "ACTIVE") {
    return NextResponse.json({ error: "Solo se puede producir con una versión de fórmula ACTIVA (aprobada por el Vet Jefe)" }, { status: 422 });
  }

  const orden = await prisma.balProductionOrder.create({
    data: {
      tenantId, formulaVersionId, orderedById: session.user.id,
      scheduledDate: new Date(scheduledDate), quantityKg,
      isAutoGenerated: isAutoGenerated ?? false,
    },
  });

  return NextResponse.json(orden, { status: 201 });
}
